func L(_ key: String) -> String {
    if let korean = koreanStrings[key] { return korean }
    // 마우스 버튼 이름 ("Button 4")은 번호가 들어가 표에 둘 수 없다
    if key.hasPrefix("Button "), Int(key.dropFirst(7)) != nil { return "버튼 " + key.dropFirst(7) }
    return key
}

