/// 대한민국 공휴일. 날짜가 해마다 같은 날은 규칙으로, 음력 명절·대체 공휴일·선거일은 해마다 표로 둔다.
/// 표는 2024~2027년까지라 그 뒤 해는 양력 공휴일만 나온다. 새 해 공휴일이 고시되면 `dated`에 더한다.
public enum KoreanHolidays {
    /// `2026-02-17` → `설날`. 공휴일이 아니면 nil.
    public static func name(on day: String) -> String? {
        let fixed = day.count == 10 ? Self.fixed[String(day.suffix(5))] : nil
        switch (fixed, dated[day]) {
        case let (a?, b?): return a == b ? a : a + "·" + b
        case let (a?, nil): return a
        case let (nil, b?): return b
        default: return nil
        }
    }

